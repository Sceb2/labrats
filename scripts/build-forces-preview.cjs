'use strict';
const fs=require('node:fs'),path=require('node:path'),{createHash}=require('node:crypto');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
let html=read('content-drafts/forces/template.html');
const css=[];
html=html.replace(/<link rel="stylesheet" href="([^"?]+)(?:\?[^\"]*)?">/g,(_,file)=>{css.push(file==='fonts.css'?require('./font-css.cjs')():read(file));return '';});
html=html.replace(/^[ \t]+$/gm,'');
const styles=css.join('\n');
const data=JSON.stringify(JSON.parse(read('content-drafts/forces/questions.json'))).replace(/</g,'\\u003c');
const script=require('esbuild').buildSync({entryPoints:[path.join(root,'content-drafts/forces/preview.js')],bundle:true,write:false,format:'iife',platform:'browser',target:'es2022'}).outputFiles[0].text;
const hash=s=>createHash('sha256').update(s).digest('base64');
const csp=`default-src 'none'; script-src 'sha256-${hash(script)}'; style-src 'sha256-${hash(styles)}'; style-src-attr 'unsafe-inline'; img-src data:; font-src data:; connect-src 'none'; base-uri 'none'; form-action 'none'`;
html=html.replace('</head>',`<meta http-equiv="Content-Security-Policy" content="${csp}"><style>${styles}</style></head>`);
html=html.replace('<script src="content-drafts/forces/preview.js"></script>',`<script type="application/json" id="forces-bank">${data}</script><script>${script}</script>`);
html=require('./brand-assets.cjs')(html);
fs.writeFileSync(path.join(root,'forces-draft.html'),'<!-- Generated by node scripts/build-forces-preview.cjs -->\n'+html);
console.log('Built self-contained forces-draft.html');
