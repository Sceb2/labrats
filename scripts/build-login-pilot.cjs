'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const {validatePublicConfig} = require('../src/student-identity.cjs');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const hash = text => createHash('sha256').update(text).digest('base64');

function buildLoginPilot(config = JSON.parse(read('auth-config.json')), output = path.join(root, 'student-login-pilot.html')) {
  const {url, key} = validatePublicConfig(config);
  // Only the public config request is supplied in memory. All Auth/API requests use real fetch.
  // This lets the same login bundle run from a downloaded file without a web server.
  const script = `(() => {\nconst originalFetch = window.fetch.bind(window);\nconst config = ${JSON.stringify({supabaseUrl: url, publishableKey: key})};\nwindow.fetch = (input, init) => input === 'auth-config.json'\n  ? Promise.resolve(new Response(JSON.stringify(config), {headers: {'Content-Type': 'application/json'}}))\n  : originalFetch(input, init);\n})();\n${read('student-login.js')}`;
  const css = read('styles.css') + '\n' + read('student-login.css');
  if (/<\/script/i.test(script) || /<\/style/i.test(css)) throw new Error('Cannot embed a closing HTML tag in a pilot asset.');
  const policy = `default-src 'none'; script-src 'sha256-${hash(script)}'; style-src 'sha256-${hash(css)}'; connect-src ${url}; img-src data:; base-uri 'none'; form-action 'none'; object-src 'none'`;
  let html = read('student-login.html');
  html = html.replace(/content="default-src[^\"]*"/, `content="${policy}"`)
    .replace('<title>Student sign in · Organic chemistry</title>', '<title>Fictional student login test · Organic chemistry</title>')
    .replace(/<link rel="stylesheet" href="styles\.css(?:\?v=[^"]*)?">\s*<link rel="stylesheet" href="student-login\.css(?:\?v=[^"]*)?">/, () => `<style>${css}</style>`)
    .replace('<a href="index.html">Continue browser-only practice</a>', '<span>Fictional account test · Your live revision website is unchanged</span>')
    .replace('<h1 id="login-heading">Student sign in</h1>', '<h1 id="login-heading">Test student sign in</h1>')
    .replace('<a id="continue-practice" class="btn secondary" href="index.html" hidden>Continue browser-only practice</a>', '<p id="continue-practice" hidden>Login test complete. Sign out, then return to your usual revision website to practise.</p>')
    .replace(/<script src="student-login\.js(?:\?v=[^"]*)?" defer><\/script>/, () => `<script>${script}</script>`);
  if (html.includes('href="index.html"') || html.includes('src="student-login.js"') || html.includes('<link rel="stylesheet"')) throw new Error('Pilot must not depend on neighbouring website files.');
  const notices = read('THIRD_PARTY_NOTICES.md').replace(/[&<>]/g, c => ({'&': '&amp;', '<': '&lt;', '>': '&gt;'}[c]));
  html = '<!-- Generated by npm run build:auth. Public configuration only; use fictional accounts. -->\n' + html.replace('</body>', () => `<template id="third-party-notices">${notices}</template>\n</body>`);
  fs.writeFileSync(output, html);
  return output;
}
if (require.main === module) buildLoginPilot();
module.exports = {buildLoginPilot};
