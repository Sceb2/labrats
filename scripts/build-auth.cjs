'use strict';
const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');
esbuild.buildSync({
  entryPoints: ['src/student-login.cjs'], outfile: 'student-login.js', bundle: true,
  platform: 'browser', target: ['es2022'], minify: true, legalComments: 'eof',
  banner: {js: '/* Generated by npm run build:auth. Includes @supabase/supabase-js (MIT). See THIRD_PARTY_NOTICES.md. */'}
});
const packages = [...fs.readdirSync('node_modules/@supabase').map(name => `@supabase/${name}`), 'iceberg-js', 'tslib'];
let notices = '# Third-party notices\n\nThe generated student-login.js bundles the following packages.\n';
for (const name of packages.sort()) {
  const directory = path.join('node_modules', name);
  const pkg = JSON.parse(fs.readFileSync(path.join(directory, 'package.json')));
  const license = fs.readdirSync(directory).find(filename => /^licen[cs]e(\.|$)/i.test(filename));
  if (!license) throw new Error(`Missing license for ${name}`);
  notices += `\n## ${name} ${pkg.version}\n\n\`\`\`text\n${fs.readFileSync(path.join(directory, license), 'utf8').trim()}\n\`\`\`\n`;
}
fs.writeFileSync('THIRD_PARTY_NOTICES.md', notices);
